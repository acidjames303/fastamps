// Local, user-triggered export helpers. No network calls and NEVER send messages.
export function csvCell(value) {
  const text = String(value ?? "");
  const safe = /^[\s]*[=+\-@\t\r]/.test(text) ? "'" + text : text;
  return '"' + safe.replace(/"/g, '""') + '"';
}
export function draftText(d) {
  return [d.body_text || "", d.signature_text || "", d.quoted_text || ""]
    .map(x=>x.trim()).filter(Boolean).join("\n\n");
}
export function draftsToCsv(drafts) {
  const fields=["workspace","from","to","cc","bcc","subject","body","status","scheduled_at","identity_warning"];
  const lines=[fields.map(csvCell).join(",")];
  for(const d of drafts) {
    lines.push([
      d.brand_label || d.brand_key || "",d.sender_address || "",d.recipient_to||"",
      d.recipient_cc||"",d.recipient_bcc||"",d.subject||"",draftText(d),
      d.status||"draft",d.scheduled_at||"",d.identity_warning||""
    ].map(csvCell).join(","));
  }
  return "\ufeff"+lines.join("\r\n");
}
function safeHeader(text) {
  return String(text || "").replace(/[\r\n\x00-\x1f]+/g, " ").trim();
}
function textEml(d) {
  const rows = [
    "Date: "+new Date().toUTCString(),
    "From: "+safeHeader(d.sender_address||""),
    "To: "+safeHeader(d.recipient_to||""),
    ...(d.recipient_cc?["Cc: "+safeHeader(d.recipient_cc)]:[]),
    "Subject: "+safeHeader(d.subject),
    "MIME-Version: 1.0",
    "Content-Type: text/plain; charset=UTF-8",
    "X-Unsent: 1",
    "X-Cadence-Status: "+safeHeader(d.status||"draft"),
    ...(d.identity_warning?["X-Cadence-Identity-Warning: Flagged"]:[]),
    "",
    draftText(d).replace(/\r?\n/g,"\r\n"),
  ];
  return rows.join("\r\n");
}
export function draftsToMbox(drafts) {
  // Apple Mail imports MBOX archives into an imported mailbox, not necessarily Drafts.
  return drafts.map((d)=>{
    const from="From "+(d.sender_address||"cadence-outreach@localhost")+" "+new Date().toUTCString();
    const eml=textEml(d).replace(/\r?\n/g,"\n").replace(/^From /gm,">From ");
    return from+"\n"+eml+"\n\n";
  }).join("");
}
function appleText(s) {
  return String(s??"").replace(/\r\n?/g,"\n").split("\n")
    .map(line=>'"'+line.replace(/\\/g,"\\\\").replace(/"/g,'\\"')+'"').join(" & return & ");
}
function splitEmails(text) {
  return String(text||"").split(/[,\n;]/).map(x=>x.trim()).filter(Boolean);
}
export function draftsToAppleScript(drafts,{testAddress="",testMode=false}={}) {
  if(drafts.length<1||drafts.length>50)throw new Error("Choose 1–50 drafts for a Mac Mail script.");
  if(testMode && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(testAddress.trim()))throw new Error("Add a valid test address.");
  const tasks=[];
  for(let i=0;i<drafts.length;i++){
    const d=drafts[i];
    if(d.identity_warning)throw new Error("Flagged company identities cannot be prepared for Apple Mail.");
    const to=testMode?[testAddress.trim()]:splitEmails(d.recipient_to);
    if(!to.length)throw new Error("A draft is missing a recipient.");
    const cc=testMode?[]:splitEmails(d.recipient_cc);
    const bcc=testMode?[]:splitEmails(d.recipient_bcc);
    const subject=(testMode?"[TEST "+(i+1)+"/"+drafts.length+"] ":"")+safeHeader(d.subject);
    const content=(testMode?
      "CADENCE TEST DRAFT — addressed to you, not the original prospect.\nOriginal recipient: "+safeHeader(d.recipient_to)+"\n\n":"")+draftText(d);
    const addressLines = to.map(address=>"    make new to recipient at end of to recipients with properties {address:"+appleText(address)+"}")
      .concat(cc.map(address=>"    make new cc recipient at end of cc recipients with properties {address:"+appleText(address)+"}"))
      .concat(bcc.map(address=>"    make new bcc recipient at end of bcc recipients with properties {address:"+appleText(address)+"}"));
    tasks.push(
      "  set draftMessage to make new outgoing message with properties {visible:false, subject:"+appleText(subject)+", content:"+appleText(content)+"}\n"+
      "  tell draftMessage\n"+addressLines.join("\n")+"\n  end tell\n  save draftMessage"
    );
  }
  return [
    "-- Generated by Cadence Outreach. Review in Script Editor before running.",
    "-- This script ONLY creates unsent Apple Mail drafts. It contains NO send command.",
    "-- Mail may save drafts locally or on your mail server depending on account settings.",
    "-- Test with ONE draft first; Apple Mail AppleScript behaviour can vary by macOS version.",
    "set choice to button returned of (display dialog "+appleText("Create "+drafts.length+" unsent drafts in Apple Mail? No email will be sent. Confirm the correct Mail account before manual sending.")+' buttons {"Cancel", "Create Drafts"} default button "Cancel" with icon caution)',
    'if choice is not "Create Drafts" then return',
    'tell application "Mail"',
    '  activate',
    ...tasks,
    'end tell',
    'display dialog "Draft creation attempted. Review the correct Drafts mailbox, recipients and From identity before sending anything." buttons {"OK"}',
    '',
  ].join("\n");
}
export function downloadText(name,content,mime="text/plain;charset=utf-8") {
  const url=URL.createObjectURL(new Blob([content],{type:mime}));
  const a=document.createElement("a");
  a.href=url;a.download=name;a.rel="noopener";
  document.body.appendChild(a);a.click();a.remove();
  setTimeout(()=>URL.revokeObjectURL(url),60000);
}
